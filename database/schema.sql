
-- Seahorse Chess Database Schema
-- Oracle Database Free 26ai
-- Schema: SEAHORSE_APP
-- Run only on a new, empty schema.

-- 1. PLAYER
CREATE TABLE PLAYER (
    PLAYER_ID NUMBER GENERATED BY DEFAULT ON NULL
        AS IDENTITY (START WITH 1 INCREMENT BY 1 CACHE 20),

    USERNAME VARCHAR2(50 CHAR) NOT NULL,
    DISPLAY_NAME VARCHAR2(100 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_PLAYER PRIMARY KEY (PLAYER_ID),
    CONSTRAINT UQ_PLAYER_USERNAME UNIQUE (USERNAME)
);

-- 2. GAME
CREATE TABLE GAME (
    GAME_ID NUMBER GENERATED BY DEFAULT ON NULL
        AS IDENTITY (START WITH 1 INCREMENT BY 1 CACHE 20),

    STATUS VARCHAR2(20 CHAR) NOT NULL,
    STARTED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    FINISHED_AT TIMESTAMP(6),

    CONSTRAINT PK_GAME PRIMARY KEY (GAME_ID),

    CONSTRAINT CK_GAME_STATUS CHECK (
        STATUS IN (
            'IN_PROGRESS',
            'COMPLETED',
            'ABANDONED'
        )
    ),

    CONSTRAINT CK_GAME_TIME CHECK (
        FINISHED_AT IS NULL
        OR FINISHED_AT >= STARTED_AT
    ),

    CONSTRAINT CK_GAME_COMPLETED CHECK (
        STATUS <> 'COMPLETED'
        OR FINISHED_AT IS NOT NULL
    )
);

-- 3. GAME_PLAYER
CREATE TABLE GAME_PLAYER (
    GAME_ID NUMBER NOT NULL,
    PLAYER_ID NUMBER NOT NULL,
    TURN_ORDER NUMBER(1,0) NOT NULL,
    COLOR_CODE VARCHAR2(20 CHAR) NOT NULL,
    FINAL_RANK NUMBER(1,0),

    CONSTRAINT PK_GAME_PLAYER
        PRIMARY KEY (GAME_ID, PLAYER_ID),

    CONSTRAINT FK_GP_GAME
        FOREIGN KEY (GAME_ID)
        REFERENCES GAME (GAME_ID),

    CONSTRAINT FK_GP_PLAYER
        FOREIGN KEY (PLAYER_ID)
        REFERENCES PLAYER (PLAYER_ID),

    CONSTRAINT UQ_GP_TURN
        UNIQUE (GAME_ID, TURN_ORDER),

    CONSTRAINT UQ_GP_COLOR
        UNIQUE (GAME_ID, COLOR_CODE),

    CONSTRAINT CK_GP_TURN
        CHECK (TURN_ORDER BETWEEN 1 AND 4),

    CONSTRAINT CK_GP_RANK
        CHECK (FINAL_RANK BETWEEN 1 AND 4)
);

-- Allow multiple NULL ranks,
-- but prevent duplicate assigned ranks.
CREATE UNIQUE INDEX UQ_GP_RANK_FILLED
ON GAME_PLAYER (
    CASE WHEN FINAL_RANK IS NOT NULL
         THEN GAME_ID END,

    CASE WHEN FINAL_RANK IS NOT NULL
         THEN FINAL_RANK END
);

CREATE INDEX IX_GAME_PLAYER_PLAYER
ON GAME_PLAYER (PLAYER_ID);

-- 4. GAME_MOVE
-- Reserved for future development.
CREATE TABLE GAME_MOVE (
    MOVE_ID NUMBER GENERATED BY DEFAULT ON NULL
        AS IDENTITY (START WITH 1 INCREMENT BY 1 CACHE 20),

    GAME_ID NUMBER NOT NULL,
    PLAYER_ID NUMBER NOT NULL,
    MOVE_NUMBER NUMBER(10,0) NOT NULL,
    DICE_VALUE NUMBER(1,0) NOT NULL,
    ACTION_TYPE VARCHAR2(10 CHAR) NOT NULL,
    PIECE_NUMBER NUMBER(1,0),
    FROM_POSITION VARCHAR2(40 CHAR),
    TO_POSITION VARCHAR2(40 CHAR),
    CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_GAME_MOVE
        PRIMARY KEY (MOVE_ID),

    CONSTRAINT FK_GM_PARTICIPANT
        FOREIGN KEY (GAME_ID, PLAYER_ID)
        REFERENCES GAME_PLAYER (GAME_ID, PLAYER_ID),

    CONSTRAINT UQ_GM_SEQUENCE
        UNIQUE (GAME_ID, MOVE_NUMBER),

    CONSTRAINT CK_GM_MOVE_NO
        CHECK (MOVE_NUMBER > 0),

    CONSTRAINT CK_GM_DIE
        CHECK (DICE_VALUE BETWEEN 1 AND 6),

    CONSTRAINT CK_GM_ACTION
        CHECK (ACTION_TYPE IN ('DEPLOY', 'MOVE', 'SKIP')),

    CONSTRAINT CK_GM_PIECE
        CHECK (PIECE_NUMBER BETWEEN 1 AND 4)
);

